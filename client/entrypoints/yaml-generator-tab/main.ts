import { stringify } from 'yaml';
import { resolveI18n } from '../common/i18n';
import './style.css';
import './tooltip.css';
import { mapsConfig } from '../common/config/maps';
import { presetMap } from './presets';

const NUMBER_OF_MAPS = Array.from(mapsConfig.values()).length
const NUMBER_OF_COUNTRIES = Array.from(mapsConfig.values().filter((map) => map.area.kind == "country")).length

function main() {
    document.addEventListener("DOMContentLoaded", resolveI18n)

    document.querySelector<HTMLFormElement>("form")!.reset()

    setupBigNumberSlider("progression-balancing")
    setupBigNumberSlider("medal-count", 4 * NUMBER_OF_MAPS)
    setupBigNumberSlider("plat-count", NUMBER_OF_MAPS)
    setupBigNumberSlider("accessible-countries-count", NUMBER_OF_COUNTRIES)
    setupBigNumberSlider("max-micro-countries-count")

    document.querySelector<HTMLInputElement>("#victory-condition")!.oninput = (e: InputEvent) => {
        const newValue = (e.target! as HTMLInputElement).value as "plat_count" | "medals_count"
        if (newValue == "medals_count") {
            document.getElementById("plat-count-container")!.style.display = "none"
            document.getElementById("medal-count-container")!.style.display = "flex"
            document.getElementById("include-platinums-container")!.style.display = "flex"
        } else {
            document.getElementById("plat-count-container")!.style.display = "flex"
            document.getElementById("medal-count-container")!.style.display = "none"
            console.log("pouet")
            document.getElementById("include-platinums-container")!.style.display = "none"
            document.querySelector<HTMLInputElement>("#include-platinums")!.checked = true
        }
    }

    document.querySelector("#generate-yaml-button")!.addEventListener("click", generateFile)
    document.querySelector("#load-last-yaml-button")!.addEventListener("click", loadLastYaml)
    document.querySelector("#load-preset-button")!.addEventListener("click", loadPreset)
}

export class PlayerOptions {
    constructor(
        public progression_balancing: number = 50,
        public accessibility: "full" | "minimal" = "full",
        public victory_condition: "plat_count" | "medals_count" = "plat_count",
        public medal_count: number = 20,
        public plat_count: number = 5,
        public accessible_countries_count: number = 10,
        public max_micro_countries_count: number = 3,
        public countries_max_difficulty: "hard" | "medium" | "easy" = "hard",
        public include_platinums: boolean = true,
        public local_items = [],
        public non_local_items = [],
        public start_inventory = [],
        public start_hints = [],
        public start_location_hints = [],
        public exclude_locations = [],
        public priority_locations = [],
    ) { }
}

function generateFile() {
    const playerOptions: PlayerOptions = getPlayerOptions()
    const playerName: string = document.querySelector<HTMLInputElement>("#player-name")!.value

    const data = {
        name: playerName.length > 0 ? playerName : "Player{number}",
        description: "YAML generated by geoguessr-archipelago's YAML Generator",
        game: "Geoguessr",
        Geoguessr: playerOptions
    }

    void storage.setItem("local:last-yaml-generation", data)
    const yamlData = stringify(data)

    const blob = new Blob([yamlData], { type: "application/x-yaml" })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `${playerName}.yaml`
    a.click()
    URL.revokeObjectURL(url)
}

function loadPlayerOptions(playerOptions: PlayerOptions) {
    document.querySelector<HTMLInputElement>(`#progression-balancing`)!.valueAsNumber = playerOptions.progression_balancing
    document.querySelector<HTMLInputElement>(`#accessibility`)!.value = playerOptions.accessibility
    document.querySelector<HTMLInputElement>(`#victory-condition`)!.value = playerOptions.victory_condition
    document.querySelector<HTMLInputElement>(`#medal-count`)!.valueAsNumber = playerOptions.medal_count
    document.querySelector<HTMLInputElement>(`#plat-count`)!.valueAsNumber = playerOptions.plat_count
    document.querySelector<HTMLInputElement>(`#accessible-countries-count`)!.valueAsNumber = playerOptions.accessible_countries_count
    document.querySelector<HTMLInputElement>(`#max-micro-countries-count`)!.valueAsNumber = playerOptions.max_micro_countries_count
    document.querySelector<HTMLInputElement>(`#country-max-diff`)!.value = playerOptions.countries_max_difficulty
    document.querySelector<HTMLInputElement>(`#include-platinums`)!.checked = playerOptions.include_platinums

    const inputEvent = new Event('input', {
        'bubbles': true,
        'cancelable': true
    });

    document.querySelector<HTMLInputElement>(`#progression-balancing`)!.dispatchEvent(inputEvent)
    document.querySelector<HTMLInputElement>(`#accessibility`)!.dispatchEvent(inputEvent)
    document.querySelector<HTMLInputElement>(`#victory-condition`)!.dispatchEvent(inputEvent)
    document.querySelector<HTMLInputElement>(`#medal-count`)!.dispatchEvent(inputEvent)
    document.querySelector<HTMLInputElement>(`#plat-count`)!.dispatchEvent(inputEvent)
    document.querySelector<HTMLInputElement>(`#accessible-countries-count`)!.dispatchEvent(inputEvent)
    document.querySelector<HTMLInputElement>(`#max-micro-countries-count`)!.dispatchEvent(inputEvent)
    document.querySelector<HTMLInputElement>(`#country-max-diff`)!.dispatchEvent(inputEvent)
    document.querySelector<HTMLInputElement>(`#include-platinums`)!.dispatchEvent(inputEvent)
}

async function loadLastYaml() {
    const lastYaml: any = await storage.getItem("local:last-yaml-generation")
    const playerName = lastYaml.name
    const playerOptions: PlayerOptions = lastYaml.Geoguessr

    document.querySelector<HTMLInputElement>("#player-name")!.value = playerName

    const inputEvent = new Event('input', {
        'bubbles': true,
        'cancelable': true
    });

    document.querySelector<HTMLInputElement>("#player-name")!.dispatchEvent(inputEvent)

    loadPlayerOptions(playerOptions)
}

function loadPreset() {
    const presetToLoad = document.querySelector<HTMLSelectElement>("#selected-preset")!.value

    const playerOptionsToLoad = presetMap.get(presetToLoad)
    if (playerOptionsToLoad === undefined) {
        console.error(`Unknown preset ${presetToLoad}, ignoring.`)
        return
    }

    loadPlayerOptions(playerOptionsToLoad)
}

function getPlayerOptions() {
    return new PlayerOptions(
        document.querySelector<HTMLInputElement>(`#progression-balancing`)!.valueAsNumber,
        document.querySelector<HTMLInputElement>(`#accessibility`)!.value as "full" | "minimal",
        document.querySelector<HTMLInputElement>(`#victory-condition`)!.value as "plat_count" | "medals_count",
        document.querySelector<HTMLInputElement>(`#medal-count`)!.valueAsNumber,
        document.querySelector<HTMLInputElement>(`#plat-count`)!.valueAsNumber,
        document.querySelector<HTMLInputElement>(`#accessible-countries-count`)!.valueAsNumber,
        document.querySelector<HTMLInputElement>(`#max-micro-countries-count`)!.valueAsNumber,
        document.querySelector<HTMLInputElement>(`#country-max-diff`)!.value as "easy" | "medium" | "hard",
        document.querySelector<HTMLInputElement>(`#include-platinums`)!.checked
    )
}

function setupBigNumberSlider(sliderId: string, maxValue?: number) {
    const slider = document.querySelector<HTMLInputElement>(`#${sliderId}`)!;
    const input = document.querySelector<HTMLInputElement>(`#${sliderId}-textbox`)!;

    if (maxValue !== undefined) {
        slider.max = maxValue.toString()
        input.max = maxValue.toString()
    } else {
        maxValue = Number.parseInt(slider.max)
    }

    slider.addEventListener("input", () => {
        input.value = slider.value;
    });

    input.addEventListener("input", () => {
        const value = Number(input.value);

        if (input.value !== "" && Number.isFinite(value)) {
            slider.valueAsNumber = Math.min(maxValue, Math.max(1, value));
        }
    });

    input.addEventListener("change", () => {
        let value = Number(input.value);

        if (input.value === "" || !Number.isFinite(value)) {
            value = Number(slider.value);
        }

        value = Math.round(Math.min(maxValue, Math.max(1, value)));

        input.valueAsNumber = value;
        slider.valueAsNumber = value;
    })
}

main()